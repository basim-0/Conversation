#!/bin/bash
# Generates the git-ignored iosApp/Configuration/Secrets.xcconfig from the same Gradle properties
# Android uses (~/.gradle/gradle.properties). Values are never printed. Missing properties stay empty.
set -euo pipefail

PROPS="${GRADLE_PROPERTIES:-$HOME/.gradle/gradle.properties}"
OUT="$(cd "$(dirname "$0")/.." && pwd)/Configuration/Secrets.xcconfig"

[ -f "$PROPS" ] || { echo "error: $PROPS not found" >&2; exit 1; }

value() { grep -E "^$1=" "$PROPS" | head -1 | cut -d= -f2- || true; }

# xcconfig treats `//` as a comment start, and base64 keys may contain it: write every `/` as `/$()`.
escape() { printf '%s' "$1" | sed 's#/#/$()#g'; }

{
  echo "// Generated by iosApp/scripts/generate-secrets.sh. Git-ignored: never commit."
  for entry in "US:AGENT_PRODUCTION" "CA:AGENT_CA_PRODUCTION" "EU:AGENT_EU_PRODUCTION" "AU:AGENT_AU_PRODUCTION" "UK:AGENT_UK_PRODUCTION"; do
    region="${entry%%:*}"; prefix="${entry##*:}"
    echo "OAUTH_${region}_CLIENT_ID = $(escape "$(value "${prefix}_CLIENT_ID")")"
    echo "OAUTH_${region}_PRIVATE_KEY = $(escape "$(value "${prefix}_PRIVATE_KEY")")"
    echo "OAUTH_${region}_KEY_ID = $(escape "$(value "${prefix}_CLIENT_KEY_ID")")"
  done
} > "$OUT"

echo "Wrote $OUT"
