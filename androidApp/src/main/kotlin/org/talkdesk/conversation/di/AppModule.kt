package org.talkdesk.conversation.di

import org.koin.dsl.module
import org.talkdesk.conversation.BuildConfig
import org.talkdesk.conversation.auth.impl.domain.model.OAuthCredentials
import org.talkdesk.conversation.auth.impl.domain.OAuthCredentialsProvider
import org.talkdesk.conversation.auth.impl.domain.model.Region

/**
 * Android composition root: what only the app can provide. Platform bindings of the shared
 * modules live in their own modules (`networkAndroidModule`, `authAndroidModule`).
 */
val appModule = module {
    single<OAuthCredentialsProvider> { BuildConfigOAuthCredentials }
}

/** Regional OAuth clients from build configuration (generated by `AndroidApplicationConventionPlugin`). */
private object BuildConfigOAuthCredentials : OAuthCredentialsProvider {
    override fun forRegion(region: Region): OAuthCredentials {
        val credentials = when (region) {
            Region.US -> OAuthCredentials(BuildConfig.OAUTH_US_CLIENT_ID, BuildConfig.OAUTH_US_PRIVATE_KEY, BuildConfig.OAUTH_US_KEY_ID)
            Region.CA -> OAuthCredentials(BuildConfig.OAUTH_CA_CLIENT_ID, BuildConfig.OAUTH_CA_PRIVATE_KEY, BuildConfig.OAUTH_CA_KEY_ID)
            Region.EU -> OAuthCredentials(BuildConfig.OAUTH_EU_CLIENT_ID, BuildConfig.OAUTH_EU_PRIVATE_KEY, BuildConfig.OAUTH_EU_KEY_ID)
            Region.AU -> OAuthCredentials(BuildConfig.OAUTH_AU_CLIENT_ID, BuildConfig.OAUTH_AU_PRIVATE_KEY, BuildConfig.OAUTH_AU_KEY_ID)
            Region.UK -> OAuthCredentials(BuildConfig.OAUTH_UK_CLIENT_ID, BuildConfig.OAUTH_UK_PRIVATE_KEY, BuildConfig.OAUTH_UK_KEY_ID)
        }
        check(credentials.clientId.isNotEmpty()) {
            "Missing OAuth credentials for $region: set AGENT_*_PRODUCTION_* in ~/.gradle/gradle.properties"
        }
        return credentials
    }
}
